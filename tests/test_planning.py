class TestEveryRowIsGrounded(unittest.TestCase):
    """Each heuristic is grounded as the path patterns are: it cites the page that states the
    location, with the date on which the page was read, quotes what decides it, and links
    files of repositories at fixed commits."""

    def test_both_files_have_rows(self):
        self.assertGreater(len(ROWS), 10)
        self.assertGreater(len(NEGATIVES), 10)

    def test_every_row_cites_a_dated_page_and_quotes_it(self):
        for row in ROWS:
            with self.subTest(pattern=row["pattern"], mode=row["match_mode"]):
                self.assertTrue(row["doc_url"].startswith("https://"))
                verified = date.fromisoformat(row["doc_verified"])
                self.assertLessEqual(verified, date.today())
                self.assertTrue(docs.quotations(row["notes"]), "the note quotes no source")

    def test_a_cited_github_page_is_a_blob_url(self):
        """The watch hashes a tree or raw URL as it is, and the hash would change for other
        reasons than a change of the document."""
        for row in [*ROWS, *NEGATIVES]:
            url = row["doc_url"]
            if url.startswith("https://github.com/"):
                with self.subTest(url=url):
                    self.assertIn("/blob/", url)

    def test_evidence_links_files_at_fixed_commits(self):
        for row in [*ROWS, *NEGATIVES]:
            for link in row["evidence"].split():
                with self.subTest(row=row["framework"], link=link):
                    self.assertRegex(link, PINNED)

    def test_every_framework_and_document_is_a_plain_name(self):
        for row in ROWS:
            with self.subTest(pattern=row["pattern"]):
                self.assertRegex(row["framework"], r"^[a-z0-9]+(-[a-z0-9]+)*$")
                self.assertRegex(row["document"], r"^[a-z0-9]+( [a-z0-9]+)*$")

    def test_the_tools_name_their_planning_features_by_their_dataset_names(self):
        """A tool's own planning feature is named as the tool columns of `repos.csv` name the
        tool, so that the two can be joined. Codex writes no plan into the repository."""
        frameworks = {row["framework"] for row in ROWS}
        self.assertEqual(frameworks & set(heuristics.TOOLS), set(heuristics.TOOLS) - {"codex"})
        self.assertFalse(frameworks & {"claude-code", "github-copilot", "gemini-cli", "codex-cli"})

    def test_the_reasons_of_layouts_that_their_sources_decide(self):
        """GSD Pi is a coding agent of its own, and Amplifier deletes its working files at the
        end. Spec Kit writes no roadmap, and Spec Kit 0.0.x installed its root files."""
        reasons = {(row["framework"], row["layout"].split(" ")[0]): row["reason"]
                   for row in NEGATIVES}
        self.assertEqual(reasons[("gsd-pi", ".gsd/**")], "out of scope")
        self.assertEqual(reasons[("amplifier", "ai_working/ddd/{plan,code_plan,docs_status,"
                                               "impl_status,test_report}.md")], "state")
        self.assertEqual(reasons[("spec-kit", "specs/<epic-slug>/roadmap.md,")],
                         "not distinctive")
        self.assertEqual(reasons[("spec-kit", "templates/,")], "configuration")
        self.assertEqual(reasons[("compound-engineering", "docs/solutions/<category>/<name>.md")],
                         "not a planning document")
        self.assertEqual(reasons[("compound-engineering",
                                  ".compound-engineering/config.yaml,")], "configuration")

    def test_kiro_is_left_out_as_a_tool_outside_the_six(self):
        kiro = [row for row in NEGATIVES if row["framework"] == "kiro"]
        self.assertEqual([row["reason"] for row in kiro], ["out of scope"])
        self.assertEqual(kiro[0]["source"], "doc")


class TestEveryQuotationIsInAPageOfItsRow(unittest.TestCase):
    """`docs --quotes --update` checks each quotation of a note against the pages that its row
    cites, its doc_url, the pages that its note links and its evidence, and records it under the
    page that contains it. The record is read here without the network."""

    RECORD = json.loads(docs.DOC_QUOTES_PATH.read_text(encoding="utf-8"))
    HASHES = json.loads(heuristics.DOC_HASHES_PATH.read_text(encoding="utf-8"))
    # The six tools, as a framework's documentation names them.
    TOOL_NAMES = re.compile(r"\b(?:Claude|Copilot|Codex|Cursor|Gemini|OpenCode)\b")
    GITHUB_FILE = re.compile(r"^https://github\.com/[^/]+/[^/]+/blob/")

    def recorded(self, url: str) -> set:
        return set((self.RECORD.get(url) or {}).get("quotations", ()))

    def found_in(self, row: dict, quotation: str) -> list:
        """The pages of the row on which the record found the quotation."""
        digest = docs.quotation_digest(quotation)
        return [url for url in docs.quote_sources(row) if digest in self.recorded(url)]

    def test_a_note_pairs_its_double_quotes(self):
        for row in [*ROWS, *NEGATIVES]:
            with self.subTest(row=row["framework"], notes=row["notes"][:60]):
                self.assertEqual(row["notes"].count('"') % 2, 0)

    def test_every_quotation_is_in_a_page_that_its_row_cites(self):
        for row in [*ROWS, *NEGATIVES]:
            for quotation in docs.quotations(row["notes"]):
                with self.subTest(row=row["framework"], quotation=quotation[:80]):
                    self.assertTrue(self.found_in(row, quotation),
                                    "run the documentation watch with --quotes --update")

    def test_every_row_quotes_its_page_or_a_file_that_its_note_links(self):
        """The text that decides a row comes from the page that it cites or from the vendor's
        file at a tag or commit that its note links."""
        for row in ROWS:
            primary = [row["doc_url"], *[url for url in docs.note_links(row["notes"])
                                         if self.GITHUB_FILE.match(url)]]
            with self.subTest(pattern=row["pattern"], mode=row["match_mode"]):
                self.assertTrue(any(set(self.found_in(row, q)) & set(primary)
                                    for q in docs.quotations(row["notes"])))

    def test_a_framework_row_quotes_a_sentence_that_names_one_of_the_six_tools(self):
        for row in ROWS:
            if row["framework"] in heuristics.TOOLS:
                continue
            with self.subTest(framework=row["framework"], pattern=row["pattern"]):
                self.assertTrue(any(self.TOOL_NAMES.search(q) and self.found_in(row, q)
                                    for q in docs.quotations(row["notes"])))

    def test_the_quotations_were_found_in_the_pages_that_the_watch_recorded(self):
        """A page that changed since its quotations were checked has a new hash in
        doc_hashes.json, and its quotations are checked again before it is recorded."""
        for row in [*ROWS, *NEGATIVES]:
            url = row["doc_url"]
            if url in self.RECORD:
                with self.subTest(url=url):
                    self.assertEqual(self.RECORD[url]["sha256"], self.HASHES[url])


class TestTheDocumentationWatchReadsBothFiles(unittest.TestCase):
    """The weekly watch fetches every page that a heuristic cites, and a page without a recorded
    hash is one that it reports as not checked."""

    def test_every_cited_page_has_a_recorded_hash(self):
        recorded = json.loads(heuristics.DOC_HASHES_PATH.read_text(encoding="utf-8"))
        for path in sorted(heuristics.HEURISTICS_DIR.glob("*.csv")):
            with open(path, newline="", encoding="utf-8") as f:
                reader = csv.DictReader(f)
                if "doc_url" not in (reader.fieldnames or []):
                    continue
                first = reader.fieldnames[0]
                urls = {row["doc_url"] for row in reader
                        if row["doc_url"] and not row[first].startswith("#")}
            with self.subTest(file=path.name):
                self.assertEqual(sorted(urls - set(recorded)), [])

    def test_the_weekly_workflow_reads_every_file_that_cites_a_page(self):
        workflow = (REPO_ROOT / ".github" / "workflows" / "doc-watch.yml").read_text(
            encoding="utf-8")
        for name, labels in (("planning_document_patterns.csv", "framework,pattern"),
                             ("not_planning_documents.csv", "framework,layout")):
            with self.subTest(name=name):
                self.assertIn(f"--heuristics heuristics/{name} \\\n"
                              f"                --label-columns {labels}", workflow)


class TestWhatTheLoaderRefuses(unittest.TestCase):
    """A row that is not grounded, or with a pattern, a match mode or an anchor that the
    matching cannot read, stops every step that loads the heuristics."""

    GOOD = {"framework": "spec-kit", "document": "spec", "pattern": r"specs/\d{3}-[^/]+/spec\.md",
            "match_mode": "with:.specify", "anchor": "", "example": "specs/001-x/spec.md",
            "doc_url": "https://example.test/page", "doc_verified": "2026-10-19",
            "evidence": "", "notes": 'It says "specs".'}
    GOOD_NEGATIVE = {"framework": "kiro", "layout": ".kiro/specs/<name>/", "example": "",
                     "reason": "out of scope", "source": "doc",
                     "doc_url": "https://example.test/kiro", "doc_verified": "2026-10-19",
                     "evidence": "", "notes": "Kiro is outside the six tools."}

    def _load(self, loader, fieldnames, good, *changes) -> str:
        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp, ignore_errors=True)
        path = tmp / "heuristics.csv"
        with open(path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            for change in changes:
                writer.writerow({**good, **change})
        try:
            loader(path)
        except ValueError as e:
            return str(e)
        return ""

    def load(self, *changes) -> str:
        return self._load(planning.load_planning_document_patterns, planning.FIELDNAMES,
                          self.GOOD, *changes)

    def load_negative(self, *changes) -> str:
        return self._load(planning_schema.load_not_planning_documents,
                          planning_schema.NOT_PLANNING_FIELDNAMES, self.GOOD_NEGATIVE, *changes)

    def test_a_grounded_row_loads(self):
        self.assertEqual(self.load({}), "")
        self.assertEqual(self.load_negative({}), "")

    def test_each_problem_is_refused(self):
        cases = {"doc_url": ({"doc_url": ""}, "doc_url"),
                 "date": ({"doc_verified": "19.10.2026"}, "doc_verified"),
                 "notes": ({"notes": " "}, "no note"),
                 "framework": ({"framework": "Spec Kit"}, "framework"),
                 "document": ({"document": "Spec"}, "document"),
                 "pattern": ({"pattern": "specs/(x"}, "no regular expression"),
                 "mode": ({"match_mode": "anywhere"}, "match mode"),
                 "marker glob": ({"match_mode": "with:*.specify"}, "glob"),
                 "setting": ({"match_mode": "setting:.claude/settings.json"}, "setting:"),
                 "anchor": ({"anchor": "near:spec.json"}, "anchor"),
                 "header": ({"anchor": "header:(unclosed"}, "no regular expression"),
                 "folder": ({"anchor": "folder_header:spec.md:^# Spec"}, "group named folder"),
                 "example": ({"example": "../x/spec.md"}, "example"),
                 "evidence": ({"evidence": "owner/repo/x.md"}, "not an https link")}
        for name, (change, message) in cases.items():
            with self.subTest(case=name):
                self.assertIn(message, self.load(change))

    def test_the_same_pattern_mode_and_anchor_twice_is_refused(self):
        self.assertIn("of an earlier row", self.load({}, {"document": "plan"}))
        self.assertEqual(self.load({}, {"document": "plan", "anchor": "header:^# Plan"}), "")

    def test_each_problem_of_a_negative_is_refused(self):
        cases = {"reason": ({"reason": "unwanted"}, "reason"),
                 "source": ({"source": "guess"}, "source"),
                 "doc": ({"doc_url": ""}, "cites no https page"),
                 "sample": ({"source": "sample", "doc_url": ""}, "no evidence"),
                 "layout": ({"layout": ""}, "no layout"),
                 "notes": ({"notes": ""}, "no note")}
        for name, (change, message) in cases.items():
            with self.subTest(case=name):
                self.assertIn(message, self.load_negative(change))


