class TestEveryRowMatchesItsOwnExample(_TreeCase):
    """For each heuristic, a tree with its example and the anchors that the row names, in which
    the heuristic, and not a row before it in the file, gives the example."""

    def tree_for(self, row: dict) -> str:
        example, mode, anchor = row["example"], row["match_mode"], row["anchor"]
        files = {example: opening(row)}
        if mode.startswith(planning.WITH_MODE):
            regex = re.compile(row["pattern"])
            parts = example.split("/")
            base = next("/".join(parts[:k]) for k in range(len(parts) - 1, -1, -1)
                        if regex.fullmatch("/".join(parts[k:])))
            marker = posixpath.join(base, mode[len(planning.WITH_MODE):].split("|")[0])
            if marker != example:
                files.setdefault(present(marker), "x\n")
        elif mode.startswith(planning.SETTING_MODE):
            settings_file, key = mode[len(planning.SETTING_MODE):].split(":")
            value = posixpath.dirname(example)
            for part in reversed(key.split(".")):
                value = {part: value}
            files[settings_file] = json.dumps(value)
        if anchor.startswith(planning.BESIDE_ANCHOR):
            name = anchor[len(planning.BESIDE_ANCHOR):].split("|")[0]
            files.setdefault(posixpath.join(posixpath.dirname(example), name), "{}\n")
        elif anchor.startswith(planning.REPOSITORY_ANCHOR):
            files.setdefault(present(anchor[len(planning.REPOSITORY_ANCHOR):].split("|")[0]),
                             "x\n")
        elif anchor.startswith(planning.FOLDER_HEADER_ANCHOR):
            match = re.compile(row["pattern"]).search(example)
            name = anchor[len(planning.FOLDER_HEADER_ANCHOR):].split(":")[0].split("|")[0]
            files[f"{example[:match.end('folder')]}/{name}"] = opening(row)
        self.write(files)
        return example

    def test_every_row_gives_its_own_example(self):
        for row in ROWS:
            with self.subTest(pattern=row["pattern"], mode=row["match_mode"],
                              anchor=row["anchor"]):
                self.fresh()
                example = self.tree_for(row)
                self.assertEqual(found(self.repo).get(example),
                                 (row["framework"], row["document"]))


