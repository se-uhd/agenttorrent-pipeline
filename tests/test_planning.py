# Every heuristic as the path heuristics keep it: its pattern, its match mode and its anchor.
TRIPLES = sorted({(row["pattern"], row["match_mode"], row["anchor"]) for row in ROWS})
# The tool directories, which the matching reads through a link (`planning.find`).
TOOL_DIRECTORIES = paths.TOOL_DIRECTORIES


def named_paths(mode: str) -> list:
    """The markers of a `with:` match mode, the settings file of a `setting:` one, else none."""
    if mode.startswith(planning.WITH_MODE):
        return mode[len(planning.WITH_MODE):].split("|")
    if mode.startswith(planning.SETTING_MODE):
        return [mode[len(planning.SETTING_MODE):].split(":")[0]]
    return []


def documented_reach(triple: tuple, paths) -> bool:
    """The reach of one changed heuristic of the planning documents as
    docs/steps/repository_cloning.md states it, read path by path: a heuristic with a marker or
    a setting reaches a file list with the marker or the settings file as whole consecutive
    components of a path, in any case, and any other a file list with a path that its pattern
    matches in full from the root, or for `any_depth` from the root or from any directory. A
    heuristic with a pattern, a marker or a settings file that begins with a tool directory also
    reaches a file list with an entry of that name at any depth and in any case, because the entry
    can be a link that the matching reads through."""
    pattern, mode, _anchor = triple
    names = named_paths(mode)
    heads = {name.split("/")[0].lower() for name in names or [planning.leading_literal(pattern)]
             if "/" in name and name.split("/")[0] in TOOL_DIRECTORIES}
    if any(path.rsplit("/", 1)[-1].lower() in heads for path in paths):
        return True
    if names:
        return any(parts[k:k + len(wanted)] == wanted
                   for parts in (path.lower().split("/") for path in paths)
                   for wanted in (name.lower().split("/") for name in names)
                   for k in range(len(parts)))
    regex = re.compile(pattern)
    if mode == planning.ROOT_MODE:
        return any(regex.fullmatch(path) for path in paths)
    return any(regex.fullmatch(path.split("/", k)[-1])
               for path in paths for k in range(path.count("/") + 1))


def example_file_lists() -> list:
    """File lists of one path built from the heuristics: each example alone, below other
    directories, in capitals and with its last character changed, and each marker and settings
    file alone and in another case below a directory."""
    lists = set()
    for row in ROWS:
        example = row["example"].replace("*", "x")
        lists |= {(example,), (f"vendor/pkg/{example}",), (example.upper(),),
                  (example[:-1] + "~",)}
        for name in named_paths(row["match_mode"]):
            lists |= {(name,), (f"pkg/{name.swapcase()}/notes.md",)}
    # An entry with the name of a tool directory, which can be a link, at the root and in capitals
    # below the root, and a path below a directory with a longer name that begins with the name of
    # the tool directory.
    for name in TOOL_DIRECTORIES:
        lists |= {(name,), (f"pkg/{name.upper()}",), (f"{name}x/notes.md",)}
    return sorted(lists)


def unreached_paths(count: int) -> list:
    """`count` paths below the first directories of the heuristics' patterns, none of them a
    marker, that no heuristic reaches, so that a reach reads every path."""
    markers = {name.lower() for row in ROWS for name in named_paths(row["match_mode"])}
    directories = sorted({literal.split("/")[0] for literal in
                          (planning.leading_literal(row["pattern"]) for row in ROWS)
                          if "/" in literal} - markers)
    return [f"{directories[i % len(directories)]}/module{i % 113}/source{i}.rs"
            for i in range(count)]


class _Passes(list):
    """A file list that counts how often it is read from its first path."""

    passes = 0

    def __iter__(self):
        self.passes += 1
        return super().__iter__()


class TestTheReachOfChangedPlanningHeuristics(unittest.TestCase):
    """The reach of the changed heuristics of the planning documents reads a repository's file
    list once however many heuristics changed, and decides for each heuristic as its documented
    reach does."""

    def test_each_heuristic_reaches_the_file_lists_that_its_documented_reach_names(self):
        lists = example_file_lists()
        wrong, unreached = [], []
        for triple in TRIPLES:
            reached = False
            for paths in lists:
                expected = documented_reach(triple, paths)
                reached |= expected
                if reuse._planning_reaches({triple}, list(paths), "\n".join(paths)) != expected:
                    wrong.append((triple, paths, expected))
            if not reached:
                unreached.append(triple)
        self.assertEqual(wrong, [])
        self.assertEqual(unreached, [], "every heuristic reaches its example or its marker")

    def test_all_heuristics_at_once_reach_what_one_of_them_reaches(self):
        for paths in example_file_lists():
            with self.subTest(paths=paths):
                self.assertEqual(
                    reuse._planning_reaches(set(TRIPLES), list(paths), "\n".join(paths)),
                    any(documented_reach(triple, paths) for triple in TRIPLES))

    def test_the_file_list_is_read_once_however_many_heuristics_changed(self):
        listed = unreached_paths(2000)
        text = "\n".join(listed)
        for count in (1, 10, len(TRIPLES)):
            with self.subTest(heuristics=count):
                paths = _Passes(listed)
                self.assertFalse(reuse._planning_reaches(set(TRIPLES[:count]), paths, text))
                self.assertEqual(paths.passes, 1)

    def test_every_heuristic_changed_over_a_large_file_list_is_decided_in_seconds(self):
        """The bound is many times what the reach that reads each path once takes over these
        paths, and a fraction of what the reach that read the list once per heuristic took."""
        entries = [("100644", path) for path in unreached_paths(100_000)]
        new = reuse.path_heuristics(heuristics.load_config_path_patterns(),
                                    heuristics.VENDORED_DIRS, ROWS)
        old = {key: value for key, value in new.items() if key != "planning"}
        started = time.monotonic()
        self.assertFalse(reuse.affected(entries, old, new))
        self.assertLess(time.monotonic() - started, 4.0)


if __name__ == "__main__":
    unittest.main()
