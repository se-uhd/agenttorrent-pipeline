def opening(row: dict) -> str:
    """The opening of a document of the row's framework and document, as it writes it."""
    return HEADERS.get((row["framework"], row["document"]),
                       HEADERS.get(row["framework"], "# A planning document\n"))


def found(tree: Path) -> dict:
    """{path: (framework, document)} of the planning documents of a tree."""
    return {rel: (row["framework"], row["document"])
            for rel, row in planning.planning_documents(tree, heuristics.VENDORED_DIRS)}


def anchors(tree: Path) -> set:
    """The anchors of the planning documents of a tree that are no planning documents."""
    return planning.find(tree, heuristics.VENDORED_DIRS)[1]


def present(path: str) -> str:
    """A file that makes `path` present: the path itself for a file name with an extension, and
    a file inside it for a directory such as `.specify`."""
    return path if "." in Path(path).name.lstrip(".") else f"{path}/README.md"


class _TreeCase(unittest.TestCase):
    """A repository's tree in a temporary directory."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.repo = self.tmp / "owner§repo"
        self.repo.mkdir()

    def write(self, files: dict) -> None:
        for rel, text in files.items():
            path = self.repo / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")

    def fresh(self) -> None:
        shutil.rmtree(self.repo)
        self.repo.mkdir()


class TestTheHeuristicsAreReadOncePerFile(_TreeCase):
    """The loader reads the file once while it is unchanged. The cleanup, the
    detection step, two checks and the fingerprint of the content quality analysis find the
    planning documents of every repository, and loading and validating the file for each
    repository would slow every pass over the sample."""

    def setUp(self):
        super().setUp()
        self.patterns = self.tmp / "planning_document_patterns.csv"
        shutil.copy(planning.PLANNING_DOCUMENT_PATTERNS_PATH, self.patterns)
        original = planning.PLANNING_DOCUMENT_PATTERNS_PATH
        planning.PLANNING_DOCUMENT_PATTERNS_PATH = self.patterns
        self.addCleanup(setattr, planning, "PLANNING_DOCUMENT_PATTERNS_PATH", original)
        self.reads, read_rows = [], planning.read_rows

        def counted(path, fieldnames):
            self.reads.append(Path(path))
            return read_rows(path, fieldnames)

        planning.read_rows = counted
        self.addCleanup(setattr, planning, "read_rows", read_rows)
        self.write({".claude/plans/feature.md": "# Plan\n\nSteps.\n"})

    def test_the_file_is_read_once_for_many_repositories(self):
        for _ in range(20):
            self.assertEqual(list(found(self.repo)), [".claude/plans/feature.md"])
        self.assertEqual(self.reads.count(self.patterns), 1)

    def test_an_edited_file_is_read_again(self):
        self.assertEqual(list(found(self.repo)), [".claude/plans/feature.md"])
        lines = self.patterns.read_text(encoding="utf-8").splitlines(keepends=True)
        self.patterns.write_text("".join(line for line in lines
                                         if not line.startswith("claude,plan,")),
                                 encoding="utf-8")
        self.assertEqual(found(self.repo), {})
        self.assertEqual(self.reads.count(self.patterns), 2)


